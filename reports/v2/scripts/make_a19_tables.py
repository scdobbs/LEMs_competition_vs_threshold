OUT: list[str] = []


def W(s: str = "") -> None:
    OUT.append(s)


def f(x, fmt=".4g"):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, np.integer)):
        return f"{x:,}"
    if isinstance(x, float):
        return format(x, fmt) if np.isfinite(x) else "-"
    return str(x)


def ci(v, fmt=".3g"):
    return f"[{f(v[0], fmt)}, {f(v[1], fmt)}]" if v else "-"


def table(headers, rows):
    W("| " + " | ".join(headers) + " |")
    W("|" + "---|" * len(headers))
    for r in rows:
        W("| " + " | ".join(str(x) for x in r) + " |")
    W()


def load(*parts):
    p = out_path(*parts)
    return load_json(p) if os.path.exists(p) else None


def cost(jobs_file: str) -> dict:
    ids = []
    if os.path.exists(jobs_file):
        for line in open(jobs_file):
            if line.strip():
                ids.append(line.split()[0])
    if not ids:
        return {}
    out = subprocess.check_output(["sacct", "-j", ",".join(ids), "-X", "-P", "-n", "--format=JobID,JobName,State,ElapsedRaw,AllocCPUS,TimelimitRaw,MaxRSS"], text=True)
    rows = []
    for line in out.strip().splitlines():
        jid, name, st, el, cpus, lim, rss = (line.split("|") + [""] * 7)[:7]
        rows.append({"job": jid, "name": name, "state": st, "elapsed_s": float(el or 0), "cpus": int(cpus or 0), "limit_min": float(lim or 0), "maxrss": rss})
    by: dict = {}
    for r in rows:
        b = by.setdefault(r["name"], {"tasks": 0, "used_h": 0.0, "limits_h": 0.0, "states": {}, "jobs": set()})
        b["tasks"] += 1
        b["used_h"] += r["elapsed_s"] * r["cpus"] / 3600
        b["limits_h"] += r["limit_min"] / 60 * r["cpus"]
        b["states"][r["state"]] = b["states"].get(r["state"], 0) + 1
        b["jobs"].add(r["job"].split("_")[0])
    for b in by.values():
        b["jobs"] = sorted(b["jobs"])
    return {"used_core_hours": sum(r["elapsed_s"] * r["cpus"] for r in rows) / 3600, "limits_core_hours": sum(r["limit_min"] / 60 * r["cpus"] for r in rows), "n_tasks": len(rows), "by_job_name": by,
            "max_rss_kb": max_rss_kb(ids)}


def max_rss_kb(ids: list[str]) -> int | None:
    """Peak MaxRSS over the job steps (sacct -X reports none on the allocation rows)."""
    out = subprocess.check_output(["sacct", "-j", ",".join(ids), "-P", "-n", "--format=MaxRSS"], text=True)
    vals = [int(v.strip().rstrip("K")) for v in out.split() if v.strip().endswith("K")]
    return max(vals, default=None)


