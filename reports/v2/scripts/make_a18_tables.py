R = run_dir()
OUT: list[str] = []


def W(s: str = "") -> None:
    OUT.append(s)


def load(*parts):
    p = os.path.join(R, *parts)
    return json.load(open(p)) if os.path.exists(p) else None


def f(x, fmt=".4g"):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, np.integer)):
        return f"{x:,}"
    if isinstance(x, float):
        if not np.isfinite(x):
            return "-"
        return format(x, fmt)
    return str(x)


def table(headers, rows):
    W("| " + " | ".join(headers) + " |")
    W("|" + "---|" * len(headers))
    for r in rows:
        W("| " + " | ".join(r) + " |")
    W()


def iv(v):
    return f"{f(v[0], '.0f')}-{f(v[1], '.0f')}" if v and v[0] is not None else "-"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=os.path.join("reports", "v2", "_appendix_a18.md"))
    a = p.parse_args()
    fits = load("summary", "per_tile_fits.json") or {}
    rules = load("summary", "rules.json") or {}
    cfg = load("prep", "configs.json")
    gm22 = load("prep", "gm22.json")
    sm22 = load("prep", "sm22.json")
    geo = load("prep", "geology.json")
    trunk = load("prep", "trunk.json")
    ttv = load("prep", "ttv_mt.json")
    sp = load("prep", "samepixel.json")
    heads = load("prep", "heads.json")
    specs = (load("prep", "fit_specs.json") or {}).get("specs", {})
    gate = load("gate", "gate.json")
    est = load("estimate", "estimate.json")
    qc = {k: load("hilltop_qc", f"{k}.json") for k in ("tiles", "pairs", "gallery", "partition")}
    tr = load("summary", "trunk.json") or {}
    cont = load("summary", "continuity.json") or {}
    tmt = load("summary", "ttv_mt.json") or {}
    hd = load("summary", "heads.json") or {}
    cost = load("summary", "cost.json") or {}

    W(f"## Appendices (generated by `reports/v2/scripts/make_a18_tables.py` from `{os.path.basename(R)}`)")
    W()
    # ------------------------------------------------------------------ C1 decisions as applied
    W("### C1. The decisions of section 1 as applied: the measured blocks (decision 9), the tiles without D0 (decision 4), the trunk list (decision 8)")
    W()
    if cfg:
        W(f"{cfg['n_written']} `measured` blocks written into `configs/tiles/<tile>.yaml` from `{cfg['source']['part_b_run']}/measure/measurement.json`; the v2.0.0 blocks of "
          f"{', '.join(cfg['old_configs_kept'])} are untouched. Loader check: {len(cfg['load_check'])} configs load; failures: {cfg['load_check_failures'] or 'none'}.")
        W()
        rows = []
        for t, v in sorted(cfg["tiles_written"].items()):
            rows.append([t, f(v["m"], ".2f"), f(v["ks"]), f(v["K0"], ".3e"), f(v["C_ht"]), f(v["D0"]), f(v["D0_B"]), f(int(v["n_hilltop_px"])), "null" if v["D0_null"] else ""])
        table(["tile", "m (site)", "k_s", "K0 = E/k_s", "C_ht(L_f)", "D0_A", "D0_B", "hilltop px", "D0"], rows)
    if trunk:
        W(f"Trunk rule: {trunk['rule']}. Trunk list (max A > 5 km2 on primary and continuity tiles): **{', '.join(trunk['trunk_list'])}** (expected {', '.join(trunk['expected'])}).")
        W()
        rows = [[t, v["site"], v["group"], f(v["max_A_km2"], ".2f"), f(v["n_cells_trunk"]), f(100 * v["frac_trunk"], ".2f") + " %", f(v["trunk_fit"])]
                for t, v in sorted(trunk["tiles"].items(), key=lambda kv: -kv[1]["max_A_km2"]) if v["max_A_km2"] > 1.0]
        table(["tile", "site", "group", "largest A (km2)", "cells A >= 1 km2", "fraction of valid cells", "trunk fit"], rows)
    # ------------------------------------------------------------------ C2 geology
    if geo:
        W("### C2. The map's description of the Paso Robles Formation labels (decision 1), from every attribute field of GEOLOGY.shp")
        W()
        fields = [x for x in geo["fields"] if x not in ("OBJECTID",)]
        rows = []
        for lab in ("QTp", "QTcl", "QTg", "QTm", "QTpc"):
            d = geo["labels"].get(lab)
            if not d:
                rows.append([lab, "0", "not in the map"])
                continue
            desc = "; ".join(f"{fl}: " + ", ".join(f"{k} ({n})" for k, n in d["values"].get(fl, {}).items()) for fl in fields if fl in d["values"])
            rows.append([lab, f(d["n_polygons"]), desc])
        table(["label", "polygons", "attribute values (count)"], rows)
    # ------------------------------------------------------------------ C3 GM 22
    if gm22:
        W("### C3. GM site summaries on the 22-tile primary set and the 19-tile clean subset (decision 1), beside the Part B 19-tile values")
        W()
        rows = []
        for name, g in gm22["groups"].items():
            k = g["ks_site_pooled_1000"]
            rows.append([name, f(g["n"]), f(k["ks"]), f"[{f(k['ks_ci95'][0])}, {f(k['ks_ci95'][1])}]" if k.get("ks_ci95") else "-", f(k.get("n_eff_centred"), ".1f"), f(g["K0_site_pooled_1000"], ".3e"),
                         f(g["K0_median"], ".3e"), f(g["D0_A_median"]), f(g["D0_B_median"]), f(g["C_ht_Lf_median"]), f"{g['window_test']['n_pass']} / {g['window_test']['n']} (non-trivial {g['window_test']['non_trivial']})",
                         f(g["per_tile_check_max_rel"], ".1e")])
        for name, g in gm22["part_b"].items():
            k = g["ks_site_pooled_1000"]
            rows.append([f"Part B {name}", f(g["n"]), f(k["ks"]), f"[{f(k['ks_ci95'][0])}, {f(k['ks_ci95'][1])}]" if k.get("ks_ci95") else "-", f(k.get("n_eff_centred"), ".1f"), f(g["K0_site_pooled_1000"], ".3e"),
                         f(g["K0_median"], ".3e"), f(g["D0_A_median"]), f(g["D0_B_median"]), f(g["C_ht_Lf_median"]), f"{g['window_test']['n_pass']} / {g['window_test']['n_tiles']}", "-"])
        table(["group", "n", "site-pooled k_s (1e3)", "95 %", "n_eff", "K0 site-pooled", "K0 median", "D0_A median", "D0_B median", "C_ht median", "window test", "k_s recheck max rel"], rows)
        if sm22:
            W("S(m) over the m-profile runs (decision 1): " + "; ".join(f"{n}: argmin {g['m_opt']:.2f}, 1 % {g['interval_0.01']['intervals']}, 5 % {g['interval_0.05']['intervals']}, "
                                                                        f"leave-one-out {min(g['leave_one_out'].values()):.2f}-{max(g['leave_one_out'].values()):.2f}" for n, g in sm22.items() if isinstance(g, dict) and "m_opt" in g))
            W()
        rows = [[t, f(v["ks_1e3"]), f(v["K0"], ".3e"), f(v["C_ht_Lf"]), f(v["D0_A"]), f(v["D0_B"]), f(int(v["n_hilltop_px"])), f(v["theta_pooled"], ".2f")] for t, v in gm22["returned_tiles"].items()]
        table(["returned tile", "k_s", "K0", "C_ht(L_f)", "D0_A", "D0_B", "hilltop px", "theta (1e3)"], rows)
        rows = [[t, v["twin"], f(v["D0_A_fema"]), f(v["D0_A_twin"]), f(v["D0_B_twin"]), f(v["D0_A_fema"] / v["D0_A_twin"], ".2f")] for t, v in gm22["ncalm_twin_D0"].items()]
        table(["FEMA tile", "NCALM twin", "D0_A FEMA", "D0_A twin", "D0_B twin", "FEMA / twin"], rows)
    # ------------------------------------------------------------------ C4 same pixel
    if sp:
        W("### C4. The same-pixel curvature diagnostic (3.1): C_ht(L_f) medians on the old and new surveys' surfaces and pixel sets")
        W()
        rows = []
        for k, v in sp["pairs"].items():
            mo = v["mapping_old_to_new"]
            rows.append([k, f(v["n_old"]), f(v["n_new"]), f(v["a"]), f(v["b"]), f(v["c"]), f(v["d"]), f(v["surface_ratios"][0], ".3f"), f(v["surface_ratios"][1], ".3f"), f(v["selection_ratios"][0], ".3f"),
                         f(v["selection_ratios"][1], ".3f"), f(v["total_ratio_d_over_a"], ".3f"), f"{mo['n_mapped']} / {mo['n_source']}", f(mo["offset_median_m"], ".2f"), f(mo["offset_max_m"], ".2f"),
                         f"{mo['n_dropped_edge']} / {mo['n_dropped_nodata']}", f(v["check_a_rel"], ".1e"), f(v["check_d_rel"], ".1e"), f(v["check_pass"])])
        table(["old / new", "n old", "n new", "(a) old on old", "(b) new on old px", "(c) old on new px", "(d) new on new", "(b)/(a)", "(d)/(c)", "(c)/(a)", "(d)/(b)", "(d)/(a)",
               "old px mapped", "offset median (m)", "offset max (m)", "dropped edge / nodata", "(a) vs Part B", "(d) vs Part B", "check"], rows)
        rows = [[k, v["label"], f(v["S_surface"], ".3f"), f(v["P_selection"], ".3f"), f(v["total_ratio_median"], ".3f"), f(v["part_b_total_ratio"], ".2f"), v["reading"]] for k, v in sp["sites"].items()]
        table(["site", "pairs", "S (surface)", "P (selection)", "total (d)/(a) median", "Part B total ratio", "reading"], rows)
        W(f"Reading rule: surface if S <= 0.85 and 0.90 <= P <= 1.10; selection if 0.90 <= S <= 1.10 and P <= 0.85; mixed otherwise. Check against Part B: tolerance {sp['tolerance_vs_part_b']}; failures: {sp['check_failures'] or 'none'}.")
        W()
    # ------------------------------------------------------------------ C5 QC figures
    if qc["tiles"]:
        W("### C5. Hilltop QC figures (3.2): the pixel classes per tile, from hilltop_qc/tiles.json")
        W()
        rows = []
        for t, v in sorted(qc["tiles"]["tiles"].items()):
            nc = v["n_class"]
            rows.append([t, v["survey"], f(v["A_c_rollover"], ".0f"), f(nc["1"]), f(nc["2"]), f(nc["3"]), f(nc["4"]), f(v["n_removed_steep"]), f(v["n_other_divides_edge"]), f(v["n_fill"]), f(v["C_ht_Lf_recomputed"]),
                         f"{t}_hilltop_qc.png"])
        table(["tile", "survey", "rollover A_c (m2)", "(i) channel", "(ii) excluded near channel", "(iii) counted hilltop", "(iv) divide dropped", "of which steep", "of which edge", "hatched (filled) cells",
               "C_ht(L_f) recomputed", "figure"], rows)
        W("Site colour scales of panel (c) (2nd-98th percentiles of the class (iii) curvature): " + "; ".join(f"{s} {v[0]:.4g}-{v[1]:.4g}" for s, v in qc["tiles"].get("site_scale", {}).items()))
        W()
        files = {}
        for _k, v in qc.items():
            if v:
                files.update(v.get("files", {}))
        big = [k for k, v in files.items() if v.get("warning")]
        W(f"{len(files)} PNG files under `reports/v2/figures/a18/hilltop_qc/`; over 5 MB: {big or 'none'}; downscaled below 200 dpi: {[k for k, v in files.items() if v['dpi'] < 200] or 'none'}.")
        W()
    # ------------------------------------------------------------------ C6 gate, C7 estimate
    if gate:
        W("### C6. The regression gate (4.1): GM1 (m = 0.31) and AP2 (PAMAP, m = 0.47) against the v2.0.0 build")
        W()
        rows = []
        for k, v in gate["tiles"].items():
            pr = v.get("part", {})
            ad = v.get("ad", {})
            rows.append([k, f(v.get("m")), f(pr.get("phase6", {}).get("A_crit")), f(pr.get("union", {}).get("A_crit")), f(pr.get("phase6", {}).get("mse"), ".10g"), f(pr.get("union", {}).get("mse"), ".10g"),
                         " ".join(f"{q} {x:.1e}" for q, x in (pr.get("rel_diff_union") or {}).items()), f(pr.get("max_rel_same_A_crit_rows"), ".1e"), f(v.get("part_pass")),
                         f(ad.get("phase6", {}).get("mse"), ".10g"), f(ad.get("new", {}).get("mse"), ".10g"), " ".join(f"{q} {x:.1e}" for q, x in (ad.get("rel_diff") or {}).items()), f(v.get("ad_pass")),
                         f"{v.get('part_run')} / {v.get('ad_run')}"])
        table(["spec", "m", "v2.0.0 A_crit", "A_crit (union)", "v2.0.0 MSE_P4", "MSE_P4 (union)", "rel diff (A_crit K D mse)", "max rel at common A_crit", "P4 pass", "v2.0.0 MSE_AD", "MSE_AD", "rel diff (K D mse r)",
               "AD pass", "runs"], rows)
        W(f"Tolerance {gate['tolerance']:g}; gate {'PASS' if gate['pass'] else 'FAIL'}.")
        W()
    if est:
        W("### C7. The cost gate (4.2): pilot timings and the expected core-hours per section, in the priority order of section 7")
        W()
        rows = [[st, site, f(v["s_per_eval_mean"], ".2f"), f(v["s_per_eval_median"], ".2f"), f(v["n_timed"]), f(v.get("n_unique_areas")), v["run"]] for st, d in est["pilot_timing"].items() for site, v in d.items()]
        table(["stage", "site (pilot tile)", "s per evaluation (mean)", "median", "n timed", "unique areas", "pilot run"], rows)
        rows = [[s["section"], f(s["n_specs"]), f(s["expected_h"], ".1f"), f(s["limits_h"], ".1f")] for s in est["sections_priority_order"]]
        table(["section", "specs", "expected core-hours", "limits (2 x estimate, 30 min floor)"], rows)
        W(f"Assumptions: {est['assumptions']['part_evals']} partitioned and {est['assumptions']['ad_evals']} AD evaluations per run. Part B expected {est['part_b_expected_h']:.1f} core-hours; Part A used at the "
          f"estimate {est['part_a_used_so_far_h']:.1f}; gate remaining {est['gate_expected_h_remaining']:.1f}; expected total {est['expected_total_h']:.1f} of {est['budget_h']:.0f} -> "
          f"{'within budget' if est['within_budget'] else 'over budget'}.")
        W()
    # ------------------------------------------------------------------ C8 primary fits per site
    def fit_rows(keys):
        rows = []
        for k in keys:
            r = fits.get(k)
            if not r or not r.get("P4") or not r.get("AD"):
                rows.append([k.split(":")[0], "incomplete"] + ["-"] * 13)
                continue
            p4, ad = r["P4"], r["AD"]
            rows.append([r["tile"] + (" [T2]" if r["tier2"] else ""), f(r["m"], ".2f"), f(p4["A_crit"], ".0f"), iv(p4.get("i1")), iv(p4.get("i5")), f(p4["mse"], ".2f"), f(ad["mse"], ".2f"), f(r["R_MSE"], ".2f"),
                         f(p4["K_over_K0"], ".2f"), f(ad["K_over_K0"], ".2f"), f(p4["D_over_D0A"], ".2f"), f(ad["D_over_D0A"], ".3g"), f(p4["D_over_D0B"], ".2f"), f(ad["D_over_D0B"], ".3g"),
                         ("" if r["has_D0"] else "no D0; ") + (f"P4 {p4['where']}; " if p4["where"] != "interior" else "") + (f"AD {ad['where']}" if ad.get("where") not in (None, "interior") else "")])
        return rows

    HDR = ["tile", "m", "A_crit (m2)", "1 % interval", "5 % interval", "MSE_P4", "MSE_AD", "R_MSE", "K/K0 P4", "K/K0 AD", "D/D0_A P4", "D/D0_A AD", "D/D0_B P4", "D/D0_B AD", "notes"]
    W("### C8. Primary fits per site (5.1): P4 and AD at the site m")
    W()
    for site in ("GM", "AP", "TTV"):
        W(f"**{site} primary ({len(PRIMARY[site])} tiles; [T2] = Tier 2, outside the clean subset)**")
        W()
        table(HDR, fit_rows([spec_key(t, "primary") for t in PRIMARY[site]]))
    W("**GM off-mesa (report only)**")
    W()
    table(HDR, fit_rows([spec_key(t, "offmesa") for t in GM_OFFMESA]))
    W("**Continuity groups (report only): NCALM GM1-GM7 at m = 0.29; PAMAP AP1-AP5 at m = 0.47; AP1_3dep**")
    W()
    table(HDR, fit_rows([spec_key(t, "ncalm") for t in GM_NCALM] + [spec_key(t, "pamap") for t in AP_PAMAP] + [spec_key(t, "ap1_3dep") for t in AP1_3DEP]))
    # ------------------------------------------------------------------ C9 variants
    W("### C9. In-sample MSE (m2) of every variant at the site m (5.2): P1 [A_crit], P2 [K, A_crit], P3 [D, A_crit], P4 [K, D, A_crit]; A1 [D], A2 [K], AD [K, D]; _A / _B = the D0 end")
    W()
    for site in ("GM", "AP", "TTV"):
        rows = []
        for t in PRIMARY[site]:
            r = fits.get(spec_key(t, "primary"))
            if not r or not r.get("P4"):
                continue
            rows.append([t + (" [T2]" if r["tier2"] else "")] + [f(r[n]["mse"], ".2f") if r.get(n) else "-" for n in ("P1_A", "P1_B", "P2_A", "P2_B", "P3", "P4", "A1", "A2_A", "A2_B", "AD")]
                        + [f(r.get("E1_A")), f(r.get("E1_B")), f(r.get("E2_P2_A")), f(r.get("E2_P2_B")), f(r.get("E2_P3")), f(r.get("F1"))])
        W(f"**{site}**")
        W()
        table(["tile", "P1_A", "P1_B", "P2_A", "P2_B", "P3", "P4", "A1", "A2_A", "A2_B", "AD", "E1_A", "E1_B", "E2 P2_A", "E2 P2_B", "E2 P3", "F1"], rows)
    W("### C9b. Parameters of every variant's optimum (primary groups)")
    W()
    rows = []
    for site in ("GM", "AP", "TTV"):
        for t in PRIMARY[site]:
            r = fits.get(spec_key(t, "primary"))
            if not r:
                continue
            for n in ("P1_A", "P1_B", "P2_A", "P2_B", "P3", "P4"):
                if r.get(n):
                    rows.append([t, n, f(r[n]["A_crit"], ".0f"), f(r[n]["K"], ".3e"), f(r[n]["D"], ".3e"), f(r[n]["mse"], ".2f"), r[n]["where"]])
            for n in ("A1", "A2_A", "A2_B", "AD"):
                if r.get(n):
                    rows.append([t, n, "-", f(r[n]["K"], ".3e"), f(r[n]["D"], ".3e"), f(r[n]["mse"], ".2f"), ("K at bound; " if r[n]["K_at_bound"] else "") + ("D at bound" if r[n]["D_at_bound"] else "")])
    table(["tile", "variant", "A_crit", "K", "D", "MSE", "where / bounds"], rows)
    # ------------------------------------------------------------------ C10 held-out
    W("### C10. Held-out (5.3): the greedy basin split and the held-out MSE (m2; fit on one half, score on the other, both ways, averaged)")
    W()
    for site in ("GM", "AP", "TTV"):
        rows = []
        for t in PRIMARY[site]:
            r = fits.get(spec_key(t, "primary"))
            if not r or not r.get("split"):
                continue
            s = r["split"]
            hp, ha = r.get("heldout_part", {}), r.get("heldout_AD") or {}
            rows.append([t, f"{s['share_h1']:.2f} / {s['share_h2']:.2f}", f(s["largest_basin_share"], ".2f"), f(s["frac_valid_in_split"], ".2f"), f"{s['n_basins_h1']} / {s['n_basins_h2']}", f(r.get("lopsided")),
                         f(hp.get("P4", {}).get("mean"), ".2f"), f(ha.get("mean"), ".2f"), f(hp.get("P2_A", {}).get("mean"), ".2f"), f(hp.get("P2_B", {}).get("mean"), ".2f"), f(r.get("H1")), f(r.get("H2_A")), f(r.get("H2_B")),
                         f"{f(hp.get('P4', {}).get('A_crit_h1'), '.0f')} / {f(hp.get('P4', {}).get('A_crit_h2'), '.0f')}",
                         f"{f(hp.get('P4', {}).get('h1_fit_score_h2'), '.1f')} / {f(hp.get('P4', {}).get('h2_fit_score_h1'), '.1f')}", f"{f(ha.get('h1_fit_score_h2'), '.1f')} / {f(ha.get('h2_fit_score_h1'), '.1f')}"])
        W(f"**{site}**")
        W()
        table(["tile", "cell shares h1 / h2", "largest basin share", "valid cells in split", "basins h1 / h2", "lopsided (< 30 %)", "P4 held-out", "AD held-out", "P2_A held-out", "P2_B held-out", "H1", "H2_A", "H2_B",
               "P4 A_crit h1 / h2", "P4 scores h1->h2 / h2->h1", "AD scores h1->h2 / h2->h1"], rows)
    # ------------------------------------------------------------------ C11 rules
    W("### C11. The rules of section 6 per site: counts, denominators and verdicts (holds = count >= 80 % of N, rounded up)")
    W()
    for site, rs in rules.items():
        for grp, r in rs.items():
            if grp == "clean_differences" or not isinstance(r, dict):
                continue
            rows = []
            for k in ("F1", "F2", "F3_A", "F3_B", "E1_A", "E1_B", "E2_P2_A", "E2_P2_B", "E2_P3"):
                v = r.get(k)
                if v:
                    extra = ""
                    if k == "F1":
                        extra = f"median R_MSE {f(v['R_MSE_median'], '.2f')}, range {f(v['R_MSE_range'][0], '.2f')}-{f(v['R_MSE_range'][1], '.2f')}" if v.get("R_MSE_range") else ""
                    if k == "F2":
                        extra = f"median K/K0 P4 {f(v['K_over_K0_median']['P4'], '.2f')}, AD {f(v['K_over_K0_median']['AD'], '.2f')}"
                    if k.startswith("F3"):
                        extra = f"median D/D0 P4 {f(v['D_over_D0_median']['P4'], '.2f')}, AD {f(v['D_over_D0_median']['AD'], '.3g')}"
                    rows.append([k, f"{v['n']} / {v['N']}", f(v["needed"]), "report only" if v.get("holds") is None else ("holds" if v["holds"] else "fails"), ", ".join(v["tiles_fail"]) or "-", extra])
            f4 = r["F4"]
