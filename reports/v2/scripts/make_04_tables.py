"""Tables for reports/v2/04_optimizer_v2.md (Phase 4, addendum 3 section 5).

Usage: PYTHONNOUSERSITE=1 LEMCVT_RESULTS=... python reports/v2/scripts/make_04_tables.py > reports/v2/04_tables.md
Reads the latest v2 `tile_run` per tile and stage (ad, partitioned, nonlinear, m_profile), the v1 reference in each
run's params.json, and the measured theta(A_c) curves from the latest measure_audit run (for V5).
Set INCLUDE_CROP=1 to include cropped smoke runs (testing only).
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np

root = Path(os.environ.get("LEMCVT_RESULTS", "/home/groups/hilley/lemcvt_results"))
INCLUDE_CROP = os.environ.get("INCLUDE_CROP") == "1"
TILES = ["AP1", "AP2", "AP3", "AP4", "AP5", "GM1", "GM2", "GM3", "GM4", "GM5"]
out: list[str] = []


def fmt(v, f=".4g"):
    return "-" if v is None or (isinstance(v, float) and not np.isfinite(v)) else format(v, f)


runs: dict[str, dict[str, tuple[str, dict, dict]]] = {}
for d in sorted(root.iterdir()):
    if "_tile_run_" not in d.name or not (d / "params.json").exists():
        continue
    try:
        p = json.loads((d / "params.json").read_text())
        r = json.loads((d / "run.json").read_text())
    except Exception:  # noqa: BLE001
        continue
    if p.get("optimizer") != "v2":
        continue
    if (r.get("config") or {}).get("crop") and not INCLUDE_CROP:
        continue
    for st in p.get("v2", {}):
        runs.setdefault(p["tile"], {})[st] = (d.name, p, r)

tiles = [t for t in TILES if t in runs]
out.append("# Tables for 04 (generated by `reports/v2/scripts/make_04_tables.py`)\n")
out.append("Runs used (latest v2 run per tile and stage):\n")
for t in tiles:
    out.append(f"- {t}: " + "; ".join(f"{st} `{name}` (git {r['git_hash'][:8]}, job {r.get('slurm_job_id')})" for st, (name, p, r) in runs[t].items()))
out.append("")


def rel(a, b):
    return (a - b) / b if (a is not None and b) else float("nan")


# ---- V1. v1 against v2, all stages
out.append("## V1. v1 (printed) against v2 (global over its grid) for every stage; 'same code' = the v1 printed point evaluated by the v2 code\n")
out.append("| tile | stage | v1 params | v1 MSE printed / same code | v2 params | v2 MSE (reduction / direct) | v2 lower? | MSE gradient at v1 point (dMSE/dlog10 K, D) | best (K, D) at v1's A_crit: MSE |")
out.append("|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    rt = runs[t]
    if "ad" in rt:
        name, p, r = rt["ad"]
        v = p["v2"]["ad"]
        ref = p["v1_reference"].get("ad", {})
        c1 = v["certificate"].get("v1_optimum", {})
        c2 = v["certificate"]["v2_optimum_direct_solve"]
        o = v["optimum"]
        out.append(f"| {t} | ad | K={fmt(ref.get('K'))}, D={fmt(ref.get('D'))} | {fmt(ref.get('MSE'))} / {fmt(c1.get('mse_same_code'), '.6g')} | "
                   f"K={o['K']:.4g}, D={o['D']:.4g} ({o.get('where')}) | {o['mse']:.6g} / {c2['mse_direct']:.6g} | "
                   f"{'yes' if c1 and o['mse'] < c1['mse_same_code'] else 'no' if c1 else '-'} ({rel(o['mse'], c1.get('mse_same_code')):+.2e}) | "
                   f"{fmt(c1.get('gradient_log10', {}).get('K'), '.3g')}, {fmt(c1.get('gradient_log10', {}).get('D'), '.3g')} | - |")
    if "partitioned" in rt:
        name, p, r = rt["partitioned"]
        v = p["v2"]["partitioned"]
        cert = v.get("certificate", {})
        s2, jo = v["stage2_optimum"], v["joint_optimum"]
        ref2 = p["v1_reference"].get("acrit", {})
        c = cert.get("v1_stage2", {})
        out.append(f"| {t} | acrit (K0, D0 fixed) | A_crit={fmt(ref2.get('A_crit'), '.6g')} | {fmt(ref2.get('MSE'))} / {fmt(c.get('mse'), '.6g')} | "
                   f"A_crit={s2['A_crit']:.6g} | {s2['mse']:.6g} / {v['direct_check']['stage2']['mse_direct']:.6g} | "
                   f"{'yes' if c and s2['mse'] < c['mse'] else 'no' if c else '-'} ({rel(s2['mse'], c.get('mse')):+.2e}) | - | - |")
        refj = p["v1_reference"].get("joint", {})
        c = cert.get("v1_joint", {})
        g = c.get("gradient_log10", {})
        b = c.get("best_at_this_A_crit", {})
        out.append(f"| {t} | joint | A_crit={fmt(refj.get('A_crit'), '.6g')}, K={fmt(refj.get('K'))}, D={fmt(refj.get('D'))} | {fmt(refj.get('MSE'))} / {fmt(c.get('mse'), '.6g')} | "
                   f"A_crit={jo['A_crit']:.6g}, K={jo['K']:.4g}, D={jo['D']:.4g} ({jo['where']}) | {jo['mse']:.6g} / {v['direct_check']['joint']['mse_direct']:.6g} | "
                   f"{'yes' if c and jo['mse'] < c['mse'] else 'no' if c else '-'} ({rel(jo['mse'], c.get('mse')):+.2e}) | "
                   f"{fmt(g.get('K'), '.3g')}, {fmt(g.get('D'), '.3g')} | K={fmt(b.get('K'))}, D={fmt(b.get('D'))}: {fmt(b.get('mse'), '.6g')} ({b.get('where')}) |")
    if "nonlinear" in rt:
        name, p, r = rt["nonlinear"]
        v = p["v2"]["nonlinear"]
        refn = p["v1_reference"].get("nonlinear", {})
        c = v["certificate"].get("v1_optimum", {})
        o = v["optimum"]
        out.append(f"| {t} | nonlinear (K0, D0, S_c) | A_crit={fmt(refn.get('A_crit'), '.6g')} | {fmt(refn.get('MSE'))} / {fmt(c.get('mse'), '.6g')} "
                   f"({c.get('picard_iterations')} it, {'converged' if c.get('converged') else 'cap'}) | A_crit={o['A_crit']:.6g} ({o['picard_iterations']} it, {'converged' if o['converged'] else 'cap'}) | {o['mse']:.6g} / - | "
                   f"{'yes' if c and o['mse'] < c['mse'] else 'no' if c else '-'} ({rel(o['mse'], c.get('mse')):+.2e}) | - | - |")
out.append("")

# ---- V2. identifiability
out.append("## V2. Identifiability: interval of A_crit (or r) within which the profile MSE is <= 1 % and <= 5 % above the minimum, and the K, D range along it\n")
out.append("| tile | profile | MSE min | 1 %: A_crit or r range (grid points, intervals) | K range | D range | 5 %: range | K range | D range |")
out.append("|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    rt = runs[t]
    rows = []
    if "partitioned" in rt:
        v = rt["partitioned"][1]["v2"]["partitioned"]
        rows.append(("joint (linear partitioned)", v["joint_identifiability"], "A_crit"))
        rows.append(("stage 2 (K0, D0 fixed)", v["stage2_identifiability"], "A_crit"))
    if "ad" in rt:
        rows.append(("AD over r = K/D", rt["ad"][1]["v2"]["ad"]["identifiability"], "r"))
    if "nonlinear" in rt:
        rows.append(("nonlinear (K0, D0 fixed)", rt["nonlinear"][1]["v2"]["nonlinear"]["identifiability"], "A_crit"))
    for label, ident, key in rows:
        cells = [label, fmt(ident["mse_min"], ".6g")]
        for lev in ("level_0.01", "level_0.05"):
            d = ident[lev]
            cells.append(f"{fmt(d.get(f'{key}_min'), '.4g')} - {fmt(d.get(f'{key}_max'), '.4g')} ({d['n_grid_points']} pts, {d['n_intervals']} int.)")
            cells.append(f"{fmt(d.get('K_min'), '.3g')} - {fmt(d.get('K_max'), '.3g')}" if "K_min" in d else "-")
            cells.append(f"{fmt(d.get('D_min'), '.3g')} - {fmt(d.get('D_max'), '.3g')}" if "D_min" in d else "-")
        out.append(f"| {t} | " + " | ".join(cells) + " |")
out.append("")

# ---- V3. exponent profile
curves = {}
aruns = sorted(d for d in root.glob("*_measure_audit_10tiles*") if (d / "params.json").exists())
if aruns:
    pa = json.loads((aruns[-1] / "params.json").read_text())
    for t, r in pa["tiles"].items():
        for est in ("pooled", "equal"):
            steps = [s for s in r["free_ladder"] if s.get(est) and s[est].get("theta_star") is not None and s[est].get("theta_ci95")]
            curves.setdefault(t, {})[est] = (np.array([s["A_c"] for s in steps]), np.array([s[est]["theta_star"] for s in steps]),
                                             np.array([s[est]["theta_ci95"][0] for s in steps]), np.array([s[est]["theta_ci95"][1] for s in steps]))


def band_at(t, est, a):
    c = curves.get(t, {}).get(est)
    if c is None:
        return None
    A, th, lo, hi = c
    la = np.log10(A)
    x = np.log10(a)
    if x < la.min() or x > la.max():
        return None
    return float(np.interp(x, la, th)), float(np.interp(x, la, lo)), float(np.interp(x, la, hi))


out.append("## V3. Exponent profile (addendum 3, 5.2): joint optimum over (A_crit, m), 1 % and 5 % contours, and the measured theta(A_c) at the fitted A_crit\n")
out.append("| tile | config m | fitted (A_crit, m) | K, D at the fit | MSE | MSE at config m (best A_crit) | 1 % contour: A_crit, m, K, D ranges | 5 % contour: A_crit, m ranges | measured theta at fitted A_crit, pooled [95 %] | equal-weight [95 %] | fitted m inside 95 % band? (pooled / equal) |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    if "m_profile" not in runs[t]:
        continue
    p = runs[t]["m_profile"][1]
    v = p["v2"]["m_profile"]
    o = v["optimum"]
    c1, c5 = v["contour_0.01"], v["contour_0.05"]
    cm = v.get("config_m_row") or {}
    bp, be = band_at(t, "pooled", o["A_crit"]), band_at(t, "equal", o["A_crit"])
    inside = []
    for b in (bp, be):
        inside.append("-" if b is None else ("yes" if b[1] <= o["m"] <= b[2] else "no"))
    out.append(f"| {t} | {p['model']['m']:.3f} | ({o['A_crit']:.4g}, {o['m']:.2f}) | K={o['K_opt']:.4g}, D={o['D_opt']:.4g} ({o['where']}) | {o['mse_joint']:.6g} | "
               f"{fmt(cm.get('mse_joint'), '.6g')} (A_crit {fmt(cm.get('A_crit'), '.4g')}) | "
               f"A_crit {c1['A_crit_min']:.4g}-{c1['A_crit_max']:.4g}, m {c1['m_min']:.2f}-{c1['m_max']:.2f}, K {c1['K_min']:.3g}-{c1['K_max']:.3g}, D {c1['D_min']:.3g}-{c1['D_max']:.3g} ({c1['n_points']} pts) | "
               f"A_crit {c5['A_crit_min']:.4g}-{c5['A_crit_max']:.4g}, m {c5['m_min']:.2f}-{c5['m_max']:.2f} | "
               f"{'-' if bp is None else f'{bp[0]:.2f} [{bp[1]:.2f}, {bp[2]:.2f}]'} | {'-' if be is None else f'{be[0]:.2f} [{be[1]:.2f}, {be[2]:.2f}]'} | {inside[0]} / {inside[1]} |")
out.append("")
out.append("### V3b. Profile MSE(m), minimised over A_crit and (K, D), relative to its minimum\n")
ms = [0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70]
out.append("| tile | " + " | ".join(f"m={m:.2f}" for m in ms) + " |")
out.append("|---|" + "---|" * len(ms))
for t in tiles:
    if "m_profile" not in runs[t]:
        continue
    pm = {round(r["m"], 2): r for r in runs[t]["m_profile"][1]["v2"]["m_profile"]["profile_m"]}
    mn = min(r["mse"] for r in pm.values())
    out.append(f"| {t} | " + " | ".join(f"{pm[m]['mse'] / mn:.3f}" if m in pm else "-" for m in ms) + " |")
out.append("")

# ---- V4. nonlinear bookkeeping and Picard
out.append("## V4. Nonlinear stage: grid, refinement, Picard cap hits, optimum\n")
out.append("| tile | unique areas in [1e2, 1e5] | grid | refine | evaluations hitting the cap | optimum A_crit (Picard it) | MSE | v1 A_crit same code: MSE (it) | 1 % interval |")
out.append("|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    if "nonlinear" not in runs[t]:
        continue
    v = runs[t]["nonlinear"][1]["v2"]["nonlinear"]
    o = v["optimum"]
    c = v["certificate"].get("v1_optimum", {})
    i1 = v["identifiability"]["level_0.01"]
    out.append(f"| {t} | {v['n_unique_in_range']} | {v['n_grid']} | {v['n_refine']} | {v['n_hit_cap']} of {v['n_evaluations']} | {o['A_crit']:.6g} ({o['picard_iterations']}) | {o['mse']:.6g} | "
               f"{fmt(c.get('A_crit'), '.6g')}: {fmt(c.get('mse'), '.6g')} ({c.get('picard_iterations')}) | {fmt(i1.get('A_crit_min'), '.4g')} - {fmt(i1.get('A_crit_max'), '.4g')} ({i1['n_grid_points']} pts) |")
out.append("")

# ---- V5. bookkeeping: grids, evaluations, wall, direct checks
out.append("## V5. Bookkeeping: A_crit grid, evaluations, wall time, reduction against direct solve\n")
out.append("| tile | stage | grid | evaluations | wall (s) | reduction vs direct: rel. MSE diff | max dz / relief (joint) | node |")
out.append("|---|---|---|---|---|---|---|---|")
for t in tiles:
    for st, (name, p, r) in runs[t].items():
        v = p["v2"][st]
        node = (r.get("slurm_accounting") or {}).get("NodeList", "?")
        if st == "partitioned":
            dc = v["direct_check"]
            out.append(f"| {t} | partitioned | {v['grid']['n_used']} of {v['grid']['n_unique']} unique ({v['grid']['mode']}) | {v['n_evaluations']} | {v['wall_s']:.0f} | "
                       f"stage2 {dc['stage2']['rel_diff']:.1e}, joint {dc['joint']['rel_diff']:.1e} | {dc['joint']['max_abs_dz_over_relief']:.1e} | {node} |")
        elif st == "ad":
            c2 = v["certificate"]["v2_optimum_direct_solve"]
            out.append(f"| {t} | ad | {v['n_grid']} r values + Brent ({v.get('brent', {}).get('nfev', '-')}) | {v['n_evaluations']} | {v['wall_s']:.0f} | {c2['rel_diff']:.1e} | - | {node} |")
        elif st == "nonlinear":
            out.append(f"| {t} | nonlinear | {v['n_grid']} + {v['n_refine']} | {v['n_evaluations']} | {v['wall_s']:.0f} | - | - | {node} |")
        elif st == "m_profile":
            out.append(f"| {t} | m_profile | {v['grid']['n_acrit']} A_crit x {len(v['grid']['m_values'])} m | {v['n_evaluations']} | {v['wall_s']:.0f} | - | - | {node} |")
# ---- V6. staircase refinement: thinned-grid optimum against the refined one
out.append("\n## V6. Staircase refinement of the thinned partitioned profile (`lemcvt tile v2-refine`): optimum on the 2000-value grid against the optimum after evaluating every unique area around the minima\n")
out.append("| tile | extra evaluations | stage 2: A_crit, MSE before -> after | joint: A_crit, MSE before -> after | joint rel. change |")
out.append("|---|---|---|---|---|")
for t in tiles:
    if "partitioned" not in runs[t]:
        continue
    v = runs[t]["partitioned"][1]["v2"]["partitioned"]
    rf = v.get("refinement")
    if not rf:
        out.append(f"| {t} | (not refined) | | | |")
        continue
    sb, jb = rf["stage2_before"], rf["joint_before"]
    s2, jo = v["stage2_optimum"], v["joint_optimum"]
    out.append(f"| {t} | {rf['n_extra']} | {sb['A_crit']:.6g}, {sb['mse']:.6g} -> {s2['A_crit']:.6g}, {s2['mse']:.6g} | "
               f"{jb['A_crit']:.6g}, {jb['mse']:.6g} -> {jo['A_crit']:.6g}, {jo['mse']:.6g} | {(jo['mse'] - jb['mse']) / jb['mse']:+.2e} |")
print("\n".join(out))
