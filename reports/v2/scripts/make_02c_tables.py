"""Build the tables of reports/v2/02c_measurement_diagnostics.md from the latest measure_diagnostics run.

Usage: PYTHONNOUSERSITE=1 LEMCVT_RESULTS=... python reports/v2/scripts/make_02c_tables.py > reports/v2/02c_tables.md
Every number in the tables comes from `<run>/params.json`; the run id is printed in the header.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np

root = Path(os.environ.get("LEMCVT_RESULTS", "/home/groups/hilley/lemcvt_results"))
runs = sorted(d for d in root.iterdir() if "_measure_diagnostics_10tiles" in d.name and (d / "run.json").exists())
run = runs[-1]
p = json.loads((run / "params.json").read_text())
meta = json.loads((run / "run.json").read_text())
tiles = list(p["tiles"])
U = {t: p["tiles"][t]["U"] for t in tiles}
STEPS = [100.0, 199.526, 398.107, 794.328, 1000.0, 1995.26, 3981.07, 7943.28, 10000.0, 19952.6, 39810.7, 100000.0]


def step(lad, a):
    d = {round(s["A_c"]): s for s in lad}
    return d.get(round(a))


def f_theta(s):
    if not s or s.get("theta_star") is None:
        return "-"
    ci = s.get("theta_ci68")
    t = f"{s['theta_star']:.2f}"
    if ci:
        t += f" [{ci[0]:.2f}, {ci[1]:.2f}]"
    return t + (f" ({s['n_basins']})" if s.get("flag_few_basins") else "")


def f_ks(s):
    if not s or s.get("ks") is None:
        return "-"
    return f"{s['ks']:.3g}"


out = []
out.append(f"# Tables for 02c (generated by `reports/v2/scripts/make_02c_tables.py` from run `{run.name}`, git {meta['git_hash'][:8]}, Slurm job {meta.get('slurm_job_id')})\n")
st = p["settings"]
out.append("Settings: " + ", ".join(f"{k} = {v}" for k, v in st.items() if k not in ("thetas", "fine_ladder", "fixed_ladder")) + "\n")

# T1 fine ladder theta
hdr = "| tile | " + " | ".join(f"{a:.3g}" for a in STEPS) + " |"
sep = "|---|" + "---|" * len(STEPS)
out.append("## T1. Free ladder: theta* [basin-bootstrap 68 %] (n basins when fewer than 10)\n")
out.append(hdr)
out.append(sep)
for t in tiles:
    out.append(f"| {t} | " + " | ".join(f_theta(step(p['tiles'][t]['fine_ladder'], a)) for a in STEPS) + " |")
for site, pp in p["pooled"].items():
    out.append(f"| **{site} pooled** | " + " | ".join(f_theta(step(pp['ladder'], a)) for a in STEPS) + " |")
out.append("")
out.append("## T2. Free ladder: k_s(theta*) (units m^(2 theta), not comparable across columns), basins, pixels, R2\n")
out.append("| tile | A_c | theta* | k_s | basins used / total | pixels | R2 | 95 % theta |")
out.append("|---|---|---|---|---|---|---|---|")
for t in tiles:
    for a in (1000.0, 1995.26, 3981.07, 10000.0, 39810.7):
        s = step(p["tiles"][t]["fine_ladder"], a)
        if not s or s.get("theta_star") is None:
            continue
        out.append(f"| {t} | {a:.3g} | {s['theta_star']:.2f} | {s['ks']:.3g} | {s['n_basins']} / {s.get('n_basins_total')} | {s.get('n_px')} | {s['r2']:.3f} | {s.get('theta_ci95')} |")
for site, pp in p["pooled"].items():
    for a in (1000.0, 1995.26, 3981.07, 10000.0, 39810.7, 100000.0):
        s = step(pp["ladder"], a)
        out.append(f"| **{site} pooled** | {a:.3g} | {s['theta_star']:.2f} | {s['ks']:.3g} [{s['ks_ci68'][0]:.3g}, {s['ks_ci68'][1]:.3g}] | {s['n_basins']} ({s['n_tiles']} tiles) | - | {s['r2']:.3f} | {s.get('theta_ci95')} |")
out.append("")

# T3 fixed vs free
out.append("## T3. Basin-fixed ladder (basins with >= 50 channel pixels at A_c = 1e4) against the free ladder\n")
out.append("| tile | basins kept / at 1e4 | " + " | ".join(f"{a:.3g}" for a in STEPS if a <= 1e4) + " | max abs(free - fixed) |")
out.append("|---|---|" + "---|" * sum(1 for a in STEPS if a <= 1e4) + "---|")
for t in tiles:
    r = p["tiles"][t]
    fx = {round(s["A_c"]): s for s in r["fixed_ladder"]}
    fr = {round(s["A_c"]): s for s in r["fine_ladder"]}
    diffs = [abs(fr[a]["theta_star"] - fx[a]["theta_star"]) for a in fx if fr.get(a, {}).get("theta_star") is not None and fx[a].get("theta_star") is not None]
    cells = []
    for a in STEPS:
        if a > 1e4:
            continue
        s = fx.get(round(a))
        cells.append(f"{s['theta_star']:.2f} / {fr[round(a)]['theta_star']:.2f}" if s and s.get("theta_star") is not None else "-")
    out.append(f"| {t} | {r['fixed_basins']['n_kept']} / {r['fixed_basins']['n_basins_at_ref']} | " + " | ".join(cells) + f" | {max(diffs):.2f} |")
out.append("\n(cells: fixed / free)\n")

# T4 scaling break
out.append("## T4. Slope-area scaling break above the rollover (2-segment break; BIC-best model; pixel-bootstrap 68 % of log10 A_break)\n")
out.append("| tile | rollover (m^2) | range | best (BIC) | A_break (m^2) | 68 % | slope below / above | A S^2 at break: median [16-84 %] |")
out.append("|---|---|---|---|---|---|---|---|")
for t in tiles + list(p["pooled"]):
    src = p["tiles"][t] if t in p["tiles"] else p["pooled"][t]
    for key, rng in (("scaling_break", "all A"), ("scaling_break_le1e5", "A <= 1e5")):
        sb = src[key]
        two = sb.get("two", {})
        bb = sb.get("break_bootstrap", {})
        ci = bb.get("ci68_log10A")
        as2 = sb.get("A_S2_at_break", {})
        name = t if t in p["tiles"] else f"**{t} pooled**"
        out.append(f"| {name} | {sb['A_rollover']:.3g} | {rng} | {sb.get('bic_best')} | {sb.get('break_A_m2', float('nan')):.3g} | "
                   f"[{10 ** ci[0]:.3g}, {10 ** ci[1]:.3g}] | {two.get('slope_below', float('nan')):.3f} / {two.get('slope_above', float('nan')):.2f} | "
                   f"{as2.get('median', float('nan')):.3g} [{as2.get('q16', float('nan')):.3g}, {as2.get('q84', float('nan')):.3g}] |")
out.append("")

# T5 common theta
out.append("## T5. Common-theta steepness k_sn (pooled through-origin chi-z slope at a fixed theta; for comparison only)\n")
out.append("| tile | A_c (site break, A <= 1e5) | k_sn(0.45) | k_sn(theta_site) | theta_site | basins | A_c = 1e4: k_sn(0.45) | k_sn(theta_site) | basins |")
out.append("|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    kc = p["tiles"][t]["ks_common_theta"]
    b = kc.get("site_break_le1e5", {})
    k4 = kc.get("1e4", {})
    th_key_b = [k for k in b if k.startswith("theta_site_")]
    th_key_4 = [k for k in k4 if k.startswith("theta_site_")]
    out.append(f"| {t} | {b.get('A_c', float('nan')):.3g} | {b['theta_0.45']['ks']:.3g} | {b[th_key_b[0]]['ks']:.3g} | {th_key_b[0].split('_')[-1]} | {b['theta_0.45']['n_basins']} | "
               f"{k4['theta_0.45']['ks']:.3g} | {k4[th_key_4[0]]['ks']:.3g} | {k4['theta_0.45']['n_basins']} |")
out.append("")

# T6 truncation
out.append("## T6. Edge truncation: fraction of channel pixels in basins whose catchment is cut by the tile edge\n")
out.append("| tile | basins (edge outlets) | truncated | interior | 1e2 | 1e3 | 1e4 | 1e5 | interior-only theta at 1e3 | at 1e4 |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
for t in tiles:
    r = p["tiles"][t]
    tb = {round(x["A_c"]): x for x in r["truncation_by_step"]}
    il = {round(s["A_c"]): s for s in r["interior_ladder"]}
    out.append(f"| {t} | {r['truncation_basins']['n_basins']} | {r['truncation_basins']['n_truncated']} | {r['truncation_basins']['n_interior']} | "
               + " | ".join(f"{tb[a]['frac_in_truncated_basins']:.2f}" for a in (100, 1000, 10000, 100000))
               + f" | {f_theta(il.get(1000))} | {f_theta(il.get(10000))} |")
out.append("")

# T7 curvature synthetic
out.append("## T7. Parabolic-ridge test: bias of the recovered crest curvature at each tile's L*\n")
out.append("| tile | L* (m) | hilltop width 2d: 10 / 25 / 50 / 75 / 90 % (m) | bias at median width | bias at 25 % width | width below which bias < -10 % | hilltop pixels in that regime |")
out.append("|---|---|---|---|---|---|---|")
for site, sy in p["synthetic_ridges"].items():
    var = "tin_noise" if site == "AP" else "noise"
    for t in [tt for tt in tiles if tt.startswith(site)]:
        Ws = np.array([c["width_m"] for c in sy["cases"]])
        b = np.array([c["bias_at_L_star"][var][t] for c in sy["cases"]])
        o = np.argsort(Ws)
        Ws, b = Ws[o], b[o]
        idx = np.where(b > -0.10)[0]
        W10 = float(Ws[idx[0]]) if idx.size else float("nan")
        wp = p["tiles"][t]["hilltop_widths_1e4"]["width_percentiles_2x_m"]
        qs = sorted(int(k) for k in wp)
        vals = np.array([wp[str(q)] for q in qs])
        frac = float(np.interp(W10, vals, np.array(qs) / 100.0))
        med = wp["50"]
        out.append(f"| {t} | {p['tiles'][t]['curvature_scale_curve']['L_star_m']:.0f} | {wp['10']:.0f} / {wp['25']:.0f} / {wp['50']:.0f} / {wp['75']:.0f} / {wp['90']:.0f} | "
                   f"{float(np.interp(med, Ws, b)) * 100:+.1f} % | {float(np.interp(wp['25'], Ws, b)) * 100:+.0f} % | {W10:.0f} m | {frac * 100:.0f} % |")
    out.append(f"\n{site}: c_true = {sy['c_true']:.3g} 1/m (the site's median C_ht), facet length {sy['facet_len_m']:.2f} m, noise sigma {sy['noise_sigma']:.3f} m; variant `{var}`.\n")

# T8 options for the threshold rule
out.append("## T8. Options for the threshold rule: theta, k_s and K0 = U/k_s per tile (from the free ladder; K0 in the model's units)\n")
opts = [("(a) A_c = 1e3 m^2", lambda t: step(p["tiles"][t]["fine_ladder"], 1000.0)),
        ("(b) A_c = 1e4 m^2", lambda t: step(p["tiles"][t]["fine_ladder"], 10000.0)),
        ("(c) site break, A <= 1e5 (AP 2.2e3, GM 447)", lambda t: step(p["tiles"][t]["fine_ladder"], 1995.26 if t.startswith("AP") else 398.107)),
        ("(d) rollover (hollow network; 02b values)", None)]
out.append("| tile | U | " + " | ".join(f"{o[0]}: theta / k_s / K0" for o in opts[:3]) + " |")
out.append("|---|---|" + "---|" * 3)
for t in tiles:
    cells = []
    for name, fn in opts[:3]:
        s = fn(t)
        if s and s.get("ks"):
            cells.append(f"{s['theta_star']:.2f} / {s['ks']:.3g} / {U[t] / s['ks']:.3g} (n={s['n_basins']})")
        else:
            cells.append("-")
    out.append(f"| {t} | {U[t]:.3g} | " + " | ".join(cells) + " |")
out.append("\n(c) uses the ladder step nearest the pooled site break (AP: 1995 m^2 for 2239; GM: 398 m^2 for 447). (d) is in `02b_measurement_first_results.md`, table 2.\n")
print("\n".join(out))
